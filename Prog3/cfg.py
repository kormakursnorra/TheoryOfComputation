def generate_random_cnf_grammar(num_non_terminals, terminals=['a', 'b', 'c']):
    import random

    non_terminals = [f'N{i}' for i in range(num_non_terminals)]
    # terminals = random.sample(string.ascii_lowercase, num_terminals)

    num_rules = random.randint(num_non_terminals, num_non_terminals * 10)
    rules = {nt: [] for nt in non_terminals}

    for _ in range(num_rules):
        lhs = random.choice(non_terminals)
        if random.random() < 0.5 and len(terminals) > 0:
            # Terminal production
            rhs = (random.choice(terminals),)
        else:
            # Non-terminal production
            rhs = (random.choice(non_terminals), random.choice(non_terminals))
        rules[lhs].append(rhs)

    start_symbol = random.choice(non_terminals)
    return rules, start_symbol



def generate_random_string(length, terminals=['a', 'b', 'c']):
    import random
    return [random.choice(terminals) for _ in range(length)]

